#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 ]]; then
  echo "Usage: $0 <case_dir>" >&2
  exit 1
fi

case_dir="$1"
anchors_json="$case_dir/parsed/anchors.json"
refs_json="$case_dir/parsed/refs.json"
stub_tex="$case_dir/rebuild/recovered_stub.tex"

if [[ ! -f "$anchors_json" ]]; then
  echo "Missing anchors json: $anchors_json" >&2
  exit 1
fi

python3 - "$anchors_json" "$refs_json" "$stub_tex" <<'PY'
import json
import sys
import unicodedata
from pathlib import Path

anchors = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
refs = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))
stub_path = Path(sys.argv[3])

UNICODE_ASCII_MAP = {
    "∼": "~",
    "−": "-",
    "γ": "gamma",
    "α": "alpha",
    "β": "beta",
    "λ": "lambda",
    "µ": "mu",
    "σ": "sigma",
    "τ": "tau",
    "ϕ": "phi",
    "∗": "*",
    "†": "+",
    "→": "->",
    "≤": "<=",
    "≥": ">=",
    "×": "x",
}

def ascii_safe(text: str) -> str:
    normalized = "".join(UNICODE_ASCII_MAP.get(ch, ch) for ch in text)
    normalized = unicodedata.normalize("NFKD", normalized)
    return normalized.encode("ascii", "ignore").decode("ascii")

def esc(text: str) -> str:
    text = ascii_safe(text)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    out = text
    for src, dst in replacements.items():
        out = out.replace(src, dst)
    return out

def split_caption(text: str, fallback_kind: str) -> tuple[str, str]:
    cleaned = ascii_safe(text).strip()
    if ":" in cleaned:
        cleaned = cleaned.split(":", 1)[1].strip()
    if "." in cleaned:
        first, rest = cleaned.split(".", 1)
        short = first.strip() or f"Recovered {fallback_kind}"
        note = rest.strip()
    else:
        short = cleaned or f"Recovered {fallback_kind}"
        note = ""
    return short, note

anchors_by_kind = {"equation": [], "figure": [], "table": [], "algorithm": []}
for anchor in anchors["anchors"]:
    anchors_by_kind.setdefault(anchor["kind"], []).append(anchor)

lines = [
    r"\documentclass[a4paper]{article}",
    r"\usepackage{amsmath}",
    r"\usepackage{amssymb}",
    r"\usepackage{graphicx}",
    r"\usepackage{booktabs}",
    r"\usepackage{float}",
    r"\usepackage{hyperref}",
    r"\usepackage{algorithm}",
    r"\usepackage{algpseudocode}",
    r"\newcommand{\EqRef}[1]{Eq.~\eqref{#1}}",
    r"\newcommand{\FigRef}[1]{Fig.~\ref{#1}}",
    r"\newcommand{\TblRef}[1]{Table~\ref{#1}}",
    r"\newcommand{\AlgRef}[1]{Algorithm~\ref{#1}}",
    r"\newcommand{\floatnote}[1]{\par\smallskip\footnotesize\noindent #1\par\normalsize}",
    r"\floatname{algorithm}{Algorithm}",
    r"\begin{document}",
    r"\section*{Recovered PDF-to-TeX Stub}",
    "This stub is generated by pdf-tex-rebuild for anchor recovery and later manual reconstruction.",
    "",
    rf"% source_pdf: {esc(anchors['source_pdf'])}",
    rf"% ref_counts: {esc(json.dumps(refs['counts'], ensure_ascii=False))}",
    "",
]

if anchors_by_kind["equation"]:
    lines.extend([r"\section*{Equations}", ""])
    for anchor in anchors_by_kind["equation"]:
        num = anchor["number"]
        lines.extend([
            rf"% page {anchor['page']} line {anchor['line_number']}",
            r"\begin{equation}",
            rf"\tag{{{num}}}\label{{{anchor['label']}}}",
            rf"\text{{TODO: recover equation {num}. Extracted line: {esc(anchor['text'])}}}",
            r"\end{equation}",
            "",
        ])

if anchors_by_kind["figure"]:
    lines.extend([r"\section*{Figures}", ""])
    last = None
    for anchor in anchors_by_kind["figure"]:
        num = int(anchor["number"])
        short_caption, note = split_caption(anchor["text"], "figure")
        if last != num:
            lines.append(rf"\setcounter{{figure}}{{{num - 1}}}")
            last = num
        lines.extend([
            rf"% page {anchor['page']} line {anchor['line_number']}",
            r"\begin{figure}[H]",
            r"\centering",
            r"\fbox{\parbox{0.85\linewidth}{TODO: recover figure asset}}",
            rf"\caption{{{esc(short_caption)}}}",
            rf"\label{{{anchor['label']}}}",
            rf"\floatnote{{{esc(note)}}}" if note else "% no figure note",
            r"\end{figure}",
            "",
        ])

if anchors_by_kind["table"]:
    lines.extend([r"\section*{Tables}", ""])
    last = None
    for anchor in anchors_by_kind["table"]:
        num = int(anchor["number"])
        if last != num:
            lines.append(rf"\setcounter{{table}}{{{num - 1}}}")
            last = num
        lines.extend([
            rf"% page {anchor['page']} line {anchor['line_number']}",
            r"\begin{table}[H]",
            r"\centering",
            r"\caption{" + esc(anchor["text"]) + r"}",
            rf"\label{{{anchor['label']}}}",
            r"\begin{tabular}{ll}",
            r"\toprule",
            r"TODO & recover table body \\",
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ])

if anchors_by_kind["algorithm"]:
    lines.extend([r"\section*{Algorithms}", ""])
    for anchor in anchors_by_kind["algorithm"]:
        short_caption, note = split_caption(anchor["text"], "algorithm")
        lines.extend([
            rf"% page {anchor['page']} line {anchor['line_number']}",
            r"\begin{algorithm}[H]",
            rf"\caption{{{esc(short_caption)}}}",
            rf"\label{{{anchor['label']}}}",
            rf"\floatnote{{{esc(note)}}}" if note else "% no algorithm note",
            r"\begin{algorithmic}[1]",
            r"\State TODO: recover algorithm body",
            r"\end{algorithmic}",
            r"\end{algorithm}",
            "",
        ])

lines.extend([r"\section*{Reference Inventory}", ""])
for item in refs["references"][:200]:
    label = item["target_label"] if item["target_label"] else "UNRESOLVED"
    lines.append(
        rf"% page {item['page']} line {item['line_number']} -> {item['kind']} {item['number']} -> {esc(label)} via {esc(item['pattern'])}"
    )

lines.extend(["", r"\end{document}", ""])
stub_path.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {stub_path}")
PY
